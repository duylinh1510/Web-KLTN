def run_inference(messages):
    """Chạy model inference từ messages, trả về cypher đã extract"""
    try:
        # Apply chat template và tokenize (trả tensor trực tiếp)
        inputs = tokenizer.apply_chat_template(
            messages,
            tokenize=True,
            add_generation_prompt=True,
            return_tensors="pt",
        ).to(model.device)

        # Create attention mask
        attention_mask = (inputs != tokenizer.pad_token_id).long()

        with torch.no_grad():
            outputs = model.generate(
                input_ids=inputs,
                attention_mask=attention_mask,
                max_new_tokens=256,
                do_sample=False,
                use_cache=True,
                pad_token_id=tokenizer.eos_token_id,
            )

        # Decode full output (giữ special tokens để extract_cypher parse)
        raw_output = tokenizer.decode(outputs[0], skip_special_tokens=False)

        # Extract cypher từ raw output
        cypher = extract_cypher(raw_output, model_name="qwen")
        question = extract_question_from_messages(messages)
        cypher = repair_graph_return_for_visual_questions(cypher, question)
        return cypher

    except Exception as e:
        print(f"Inference error: {e}")
        return "error"


def extract_question_from_messages(messages):
    """Extract the active user question from generation/correction prompts."""
    if not messages:
        return ""
    content = str(messages[-1].get("content", ""))

    original_matches = re.findall(
        r"Original Question:\s*(.*?)\n",
        content,
        flags=re.IGNORECASE | re.DOTALL,
    )
    if original_matches:
        return original_matches[-1].strip()

    question_matches = re.findall(
        r"Question:\s*(.*?)\nCypher output:",
        content,
        flags=re.IGNORECASE | re.DOTALL,
    )
    if question_matches:
        return question_matches[-1].strip()

    return ""


def repair_graph_return_for_visual_questions(cypher: str, question: str) -> str:
    """For graph/connected questions, return nodes + relationship variables."""
    if not cypher or cypher in ["time_error", "error"]:
        return cypher

    q = (question or "").lower()
    wants_graph = any(
        token in q
        for token in [
            "graph",
            "network",
            "connected",
            "connection",
            "relationship",
            "visualize",
            "visualise",
        ]
    )
    if not wants_graph:
        return cypher

    pattern = re.compile(
        r"\(([A-Za-z_][A-Za-z0-9_]*)\:Transaction\)\s*-\s*\[(?:([A-Za-z_][A-Za-z0-9_]*)\s*)?\:(HAS_[A-Z0-9_]+)\]\s*->\s*\(([A-Za-z_][A-Za-z0-9_]*)\:([A-Za-z_][A-Za-z0-9_]*Node)\)",
        flags=re.IGNORECASE,
    )
    match = pattern.search(cypher)
    if not match:
        return cypher

    tx_alias = match.group(1)
    rel_alias = match.group(2) or "r"
    aux_alias = match.group(4)
    rel_type = match.group(3)
    aux_label = match.group(5)

    if not match.group(2):
        cypher = pattern.sub(
            f"({tx_alias}:Transaction)-[{rel_alias}:{rel_type}]->({aux_alias}:{aux_label})",
            cypher,
            count=1,
        )

    prefix = re.split(r"\bRETURN\b", cypher, maxsplit=1, flags=re.IGNORECASE)[0].strip()
    limit_match = re.search(r"\bLIMIT\s+\d+\b", cypher, flags=re.IGNORECASE)
    limit_clause = limit_match.group(0) if limit_match else "LIMIT 50"
    return f"{prefix} RETURN {tx_alias}, {rel_alias}, {aux_alias} {limit_clause}".strip()


