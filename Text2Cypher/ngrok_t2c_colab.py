MODEL_TOKENS = {
    "qwen": {
        "start": "<|im_start|>assistant",
        "end": "<|im_end|>",
        "special_tokens": ["<|im_end|>", "<|im_start|>", "<|eot_id|>", "<|start_header_id|>", "<|end_header_id|>", "<|endoftext|>"]
    },
}

def extract_cypher(text, model_name="qwen"):
    if text in ["time_error", "error"]:
        return text

    try:
        tokens = MODEL_TOKENS[model_name]
        if tokens["start"] in text:
            after_assistant = text.split(tokens["start"])[-1]
            if tokens["end"] in after_assistant:
                assistant_content = after_assistant.split(tokens["end"])[0].strip()
            else:
                assistant_content = after_assistant.strip()
        else:
            assistant_content = text.strip()

        # Extract code block (giữa ``` ```)
        match = re.search(r"```(.*?)```", assistant_content, re.DOTALL)
        if match:
            code_block = match.group(1).strip()
        else:
            code_block = assistant_content.strip()

        # Tìm "MATCH" và trích xuất Cypher
        code_block_lower = code_block.lower()
        match_index = code_block_lower.find("match")
        if match_index == -1:
            return "error"

        cypher = code_block[match_index:].strip()

        # Loại bỏ special tokens
        for token in tokens["special_tokens"]:
            cypher = cypher.replace(token, "")
        cypher = cypher.strip()
        cypher = repair_common_cypher_issues(cypher)

        return cypher
    except:
        return "error"


def repair_common_cypher_issues(cypher: str) -> str:
    """Fix small syntax slips that the LLM often makes during correction."""
    if not cypher or cypher in ["time_error", "error"]:
        return cypher

    # Keep only the first Cypher statement if the model adds trailing text.
    if ";" in cypher:
        cypher = cypher.split(";", 1)[0]

    # Example:
    #   MATCH (t:Transaction)-[:HAS_CATEGORY]->(c:CategoryNode WHERE ...
    #   MATCH (t:Transaction)-[:HAS_CATEGORY]->(c:CategoryNode) WHERE ...
    cypher = re.sub(
        r"\(([A-Za-z_][A-Za-z0-9_]*)\:([A-Za-z_][A-Za-z0-9_]*)(\s+)(WHERE|WITH|RETURN|ORDER\s+BY|LIMIT)\b",
        r"(\1:\2) \4",
        cypher,
        flags=re.IGNORECASE,
    )

    # Same repair for anonymous nodes: (:CategoryNode WHERE ...)
    cypher = re.sub(
        r"\(\:([A-Za-z_][A-Za-z0-9_]*)(\s+)(WHERE|WITH|RETURN|ORDER\s+BY|LIMIT)\b",
        r"(:\1) \3",
        cypher,
        flags=re.IGNORECASE,
    )

    cypher = repair_transaction_fraud_filters(cypher)
    cypher = repair_sql_style_fragments(cypher)

    return cypher.strip()


def repair_transaction_fraud_filters(cypher: str) -> str:
    """Normalize fraud property aliases and comparisons for Transaction aliases."""
    tx_aliases = re.findall(r"\(([A-Za-z_][A-Za-z0-9_]*)\:Transaction\)", cypher)

    for alias in tx_aliases:
        cypher = re.sub(
            rf"\b{alias}\.(isFraud|fraud|fraud_label|label)\b",
            f"{alias}.is_fraud",
            cypher,
            flags=re.IGNORECASE,
        )

        def replace_compare(match):
            op = match.group(1)
            value = match.group(2)
            if op == "!=":
                op = "<>"
            return f'toString({alias}.is_fraud) {op} "{value}"'

        cypher = re.sub(
            rf"\b{alias}\.is_fraud\s*(=|<>|!=)\s*[\"']?([01])[\"']?",
            replace_compare,
            cypher,
            flags=re.IGNORECASE,
        )

    return cypher


def repair_sql_style_fragments(cypher: str) -> str:
    """Remove small SQL habits that are invalid in Cypher."""
    cypher = re.sub(
        r"\s+GROUP\s+BY\s+.+?(?=\s+ORDER\s+BY|\s+LIMIT|$)",
        " ",
        cypher,
        flags=re.IGNORECASE,
    )
    cypher = re.sub(
        r"\bLIMIT\s+[\"'](\d+)[\"']",
        r"LIMIT \1",
        cypher,
        flags=re.IGNORECASE,
    )
    cypher = re.sub(r"\s+", " ", cypher).strip()
    return cypher


